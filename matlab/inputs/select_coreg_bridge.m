function bridgeFile = select_coreg_bridge(RAW, SUB, SES, CFG, runSel, anchor)
% SELECT_COREG_BRIDGE  The whole-brain EPI the T2w is coregistered through.
%
% COREG_VIA_TASK names the task label, so 'rest' looks for
%   func/sub-XX_ses-YY[_run-N]_task-rest_bold.nii[.gz]
%
% What matters about this image is coverage, not contrast: it has to overlap
% both the T2w slab and the task EPI slab generously, which a whole-brain
% acquisition does and a partial slab does not. A resting-state run is the
% usual candidate because it is whole-brain and already in the session.
%
% Picked with the same run-matching rules as every other scan, so when a
% session holds several of them the one acquired nearest the task runs wins.

task  = CFG.COREG_VIA_TASK;
cands = bids_list_runs({RAW.func}, struct('sub', SUB, 'ses', SES, ...
                                          'suffix', 'bold', ...
                                          'task',   task, ...
                                          'prefix', ''));

assert(~isempty(cands), [ ...
    'COREG_VIA_TASK is "%s", but no task-%s BOLD exists for %s / %s.\n' ...
    '  Searched: %s\n' ...
    'Either name a task label that is there, or set COREG_VIA_TASK= (empty) ' ...
    'to coregister the T2w straight to the session mean.'], ...
    task, task, SUB, SES, RAW.func);

[bridgeFile, info] = bids_pick_run(cands, struct( ...
    'label',      sprintf('coreg bridge (task-%s)', task), ...
    'selected',   bids_selection_for(runSel, ['task-' task], 'coreg-bridge'), ...
    'anchorSec',  anchor.secs, ...
    'anchorName', anchor.name, ...
    'gapSec',     CFG.RUN_MATCH_GAP_SEC, ...
    'strict',     CFG.STRICT_RUN_MATCHING));
fprintf('  bridge   %-10s %s\n', info.runLabel, info.reason);
end
